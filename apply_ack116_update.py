def _safe_relative(name):
    path = PurePosixPath(name)
    if (not name or "\\" in name or path.is_absolute() or
            any(part in {"", ".", ".."} for part in name.split("/")) or
            path.as_posix() != name or ":" in name):
        raise ValueError("Invalid packaged path: " + name)
    return path


def payload_files():
    raw = base64.b64decode("".join(PAYLOAD_B64.split()), validate=True)
    if hashlib.sha256(raw).hexdigest() != PAYLOAD_SHA256:
        raise ValueError("Installer payload checksum mismatch; download the complete update again.")
    files = {}
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        for info in archive.infolist():
            _safe_relative(info.filename)
            if info.filename in files or info.is_dir() or stat.S_ISLNK(info.external_attr >> 16):
                raise ValueError("Invalid or duplicate packaged entry: " + info.filename)
            files[info.filename] = archive.read(info)
    # Preserve this installer too when it was launched from outside the repo.
    files["apply_ack116_update.py"] = Path(__file__).read_bytes()
    files["ACK116_FILES.sha256"] = "".join(
        hashlib.sha256(data).hexdigest() + "  " + name + "\n"
        for name, data in sorted(files.items())
    ).encode("utf-8")
    return files


def apply_update(repo, files, *, check=False):
    root = Path(repo).resolve()
    if not (root / "app.py").is_file():
        raise ValueError("Repository root must contain app.py. Place this script there or pass --repo PATH.")
    changed = []
    for name, data in files.items():
        relative = _safe_relative(name)
        target = root.joinpath(*relative.parts)
        if target.is_symlink() or not target.resolve().is_relative_to(root):
            raise ValueError("Refusing a symlink or a path outside the repository: " + name)
        if target.exists() and not target.is_file():
            raise ValueError("Expected a file at: " + name)
        if not target.exists() or target.read_bytes() != data:
            changed.append(name)
    if check or not changed:
        return changed, None

    # Stage every byte and back up every old file before replacing any target.
    backup = Path(tempfile.mkdtemp(prefix=root.name + "-ack116-backup-", dir=root.parent))
    written = []
    with tempfile.TemporaryDirectory(prefix="ack116-stage-", dir=root.parent) as staging:
        staged = Path(staging)
        for name in changed:
            target, prepared, saved = root / name, staged / name, backup / name
            prepared.parent.mkdir(parents=True, exist_ok=True)
            prepared.write_bytes(files[name])
            prepared.chmod((target.stat().st_mode & 0o777) if target.exists() else 0o644)
            if target.exists():
                saved.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(target, saved)
        try:
            for name in changed:
                target = root / name
                target.parent.mkdir(parents=True, exist_ok=True)
                os.replace(staged / name, target)
                written.append(name)
            for name in changed:
                if (root / name).read_bytes() != files[name]:
                    raise OSError("Written file does not match packaged bytes: " + name)
        except Exception as exc:
            failures = []
            for name in reversed(written):
                try:
                    saved, target = backup / name, root / name
                    if saved.exists():
                        shutil.copy2(saved, target)
                    else:
                        target.unlink(missing_ok=True)
                except OSError:
                    failures.append(name)
            detail = " Rollback needs attention: " + ", ".join(failures) if failures else " Previous files restored."
            raise RuntimeError("Update failed." + detail + " Backup: " + str(backup)) from exc
    return changed, backup


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument("--check", action="store_true", help="read-only check; exit 1 if files need updating")
    options = parser.parse_args(argv)
    try:
        changed, backup = apply_update(options.repo, payload_files(), check=options.check)
    except (ValueError, OSError, RuntimeError, zipfile.BadZipFile) as exc:
        print("ERROR:", exc, file=sys.stderr)
        return 2
    label = "NEEDS UPDATE" if options.check else "UPDATED"
    for name in changed:
        print(label + ": " + name)
    if backup:
        print("Previous files backed up at: " + str(backup))
    print("Check complete." if options.check else "ACK116 source files are in place. Commit and deploy through your normal workflow.")
